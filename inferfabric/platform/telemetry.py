"""platform.telemetry — unified device telemetry contract (dual-platform).

Spec: docs/superpowers/specs/2026-11-18-device-telemetry-design.md §6.

Three-layer discipline (spec §5): only the Platform Adapter layer may
sense OS/hardware; gateway core consumes `DeviceTelemetry`/`DeviceControl`
via the factories below. Semantics pinned by user rulings (spec §14):

- Unavailable metric = None (JSON null), never 0 or a hardware sentinel.
- `memory_kind` decides UI/scheduling semantics: unified | vram | unknown.
- Capabilities are static per backend; per-read availability lives in
  the snapshot's None fields + `sources`.
- Observations fail open (None); control/destructive paths fail closed.
- DeviceTelemetry is read-only; DeviceControl.reset() is the only
  destructive op, NVIDIA-only this phase, Apple returns unsupported.

This module is import-safe on every platform: concrete backends load
lazily inside the factories, so no platform command runs at import time.
"""
from __future__ import annotations

import time
from dataclasses import dataclass, field
from typing import Protocol, runtime_checkable

from . import PlatformProfile

__all__ = [
    "DeviceCapabilities",
    "DeviceSnapshot",
    "OperationResult",
    "DeviceTelemetry",
    "DeviceControl",
    "NullTelemetry",
    "NullDeviceControl",
    "snapshot_to_dict",
    "capabilities_to_dict",
    "legacy_gpu_fields",
    "telemetry_for_profile",
    "device_control_for_profile",
]


# ── data contracts ───────────────────────────────────────────────

@dataclass(frozen=True)
class DeviceCapabilities:
    """Static per-backend capability declaration (spec §14.5).

    Whether a capability produced a value THIS read is expressed by the
    snapshot field being None, not by flipping these flags.
    """

    memory: bool = False
    utilization: bool = False
    power: bool = False
    temperature: bool = False
    clock: bool = False
    pressure: bool = False
    reset: bool = False


@dataclass(frozen=True)
class DeviceSnapshot:
    """One timestamped device reading; None = unavailable, never 0."""

    platform: str                     # darwin | linux | other
    accelerator: str                  # apple_silicon | nvidia | unknown
    memory_kind: str                  # unified | vram | unknown
    memory_used_mb: int | None
    memory_total_mb: int | None       # PHYSICAL total (spec §6.1)
    memory_budget_mb: int | None      # schedulable budget (Apple: B=RAM−reserve)
    utilization_pct: float | None
    power_w: float | None
    temperature_c: float | None
    clock_mhz: int | None
    pressure_level: int | None
    timestamp: float                  # generated by the sampling backend
    sources: dict[str, str] = field(default_factory=dict)  # field -> probe name


@dataclass(frozen=True)
class OperationResult:
    """Result of a device control operation (reset)."""

    ok: bool
    status: str                       # ok | unsupported | error
    message: str = ""
    details: dict | None = None


# ── protocols ────────────────────────────────────────────────────

@runtime_checkable
class DeviceTelemetry(Protocol):
    """Read-only device observation (spec §6.2)."""

    def snapshot(self) -> DeviceSnapshot: ...

    def capabilities(self) -> DeviceCapabilities: ...


@runtime_checkable
class DeviceControl(Protocol):
    """Destructive device operations; separate from telemetry by design.

    ``force`` marks caller-intentional clears (operator gpu-clear, post-stop
    fragmentation) where residual VRAM is expected — backends may skip their
    occupancy refusal for the scoped reset, but never for unscoped fallbacks
    that would widen the blast radius.
    """

    def reset(self, force: bool = False) -> OperationResult: ...


# ── serialization helpers (JSON null contract) ───────────────────

_SNAPSHOT_FIELDS = (
    "platform", "accelerator", "memory_kind",
    "memory_used_mb", "memory_total_mb", "memory_budget_mb",
    "utilization_pct", "power_w", "temperature_c", "clock_mhz",
    "pressure_level", "timestamp", "sources",
)


def snapshot_to_dict(snapshot: DeviceSnapshot) -> dict:
    """Serialize a snapshot; None stays None (never coerced to 0)."""
    return {name: getattr(snapshot, name) for name in _SNAPSHOT_FIELDS}


def capabilities_to_dict(caps: DeviceCapabilities) -> dict:
    return {
        "memory": caps.memory, "utilization": caps.utilization,
        "power": caps.power, "temperature": caps.temperature,
        "clock": caps.clock, "pressure": caps.pressure,
        "reset": caps.reset,
    }


def legacy_gpu_fields(snapshot: DeviceSnapshot) -> dict:
    """Approved legacy gpu_* mapping (spec §14.2) for one snapshot.

    unified (Apple): gpu_total_mb carries the budget B; utilization is never
    fabricated. vram: physical VRAM total + derived VRAM occupancy pct.
    Unavailable readings stay None (never 0).
    """
    if snapshot.memory_kind == "unified":
        return {"gpu_used_mb": snapshot.memory_used_mb,
                "gpu_total_mb": snapshot.memory_budget_mb,
                "gpu_util_pct": None}
    util = (snapshot.memory_used_mb / snapshot.memory_total_mb * 100
            if snapshot.memory_used_mb is not None
            and snapshot.memory_total_mb else None)
    return {"gpu_used_mb": snapshot.memory_used_mb,
            "gpu_total_mb": snapshot.memory_total_mb,
            "gpu_util_pct": util}


# ── Null backends (unknown platform / no accelerator) ────────────

class NullTelemetry:
    """All measurements None; never touches the platform."""

    def snapshot(self) -> DeviceSnapshot:
        return DeviceSnapshot(
            platform="other", accelerator="unknown", memory_kind="unknown",
            memory_used_mb=None, memory_total_mb=None, memory_budget_mb=None,
            utilization_pct=None, power_w=None, temperature_c=None,
            clock_mhz=None, pressure_level=None, timestamp=time.time(),
            sources={},
        )

    def capabilities(self) -> DeviceCapabilities:
        return DeviceCapabilities()


class NullDeviceControl:
    """Explicit unsupported — never a substitute dangerous command."""

    def reset(self, force: bool = False) -> OperationResult:
        return OperationResult(
            ok=False, status="unsupported",
            message="device reset not supported on this platform",
        )


# ── factories (the ONLY assembly points) ─────────────────────────

def telemetry_for_profile(profile: PlatformProfile) -> DeviceTelemetry:
    """Assemble the telemetry backend for a resolved profile.

    Lazy imports keep this module free of platform commands at import
    time. Unknown/other profiles get NullTelemetry. Concrete darwin/linux
    branches are wired by the platform backends (Task 2).
    """
    if profile.os == "darwin":
        from .apple_telemetry import AppleSiliconTelemetry
        return AppleSiliconTelemetry()
    if profile.os == "linux":
        from .nvidia_telemetry import NvidiaTelemetry
        return NvidiaTelemetry()
    return NullTelemetry()


def device_control_for_profile(
        profile: PlatformProfile, *, gpu_index: int = 0) -> DeviceControl:
    """Assemble the control backend; NVIDIA-only reset this phase."""
    if profile.os == "linux":
        from .nvidia_telemetry import NvidiaDeviceControl
        return NvidiaDeviceControl(gpu_index=gpu_index)
    return NullDeviceControl()
